/**
 * Main HTTP Handler
 * Compatible with Vercel serverless (req, res) and standard Node HTTP
 */
module.exports = async function handler(req, res) {
    // Enable CORS
    res.setHeader("Access-Control-Allow-Origin", "*");
    res.setHeader("Access-Control-Allow-Methods", "POST, OPTIONS");
    res.setHeader("Access-Control-Allow-Headers", "Content-Type");

    if (req.method === "OPTIONS") {
        res.statusCode = 200;
        res.end();
        return;
    }

    if (req.method !== "POST") {
        res.statusCode = 405;
        res.setHeader("Content-Type", "application/json");
        res.end(JSON.stringify({ error: "Method not allowed. Use POST." }));
        return;
    }

    // Rate limiting check
    const clientIp = req.headers["x-forwarded-for"] || req.socket?.remoteAddress || "127.0.0.1";
    if (!checkRateLimit(clientIp)) {
        res.statusCode = 429;
        res.setHeader("Content-Type", "application/json");
        res.end(JSON.stringify({ 
            error: "Too Many Requests", 
            message: "Rate limit reached (max 20 messages per minute). Please pause for a moment." 
        }));
        return;
    }

    // Read and parse request body if not already parsed
    let body = req.body;
    if (typeof body === "string") {
        try {
            body = JSON.parse(body);
        } catch (e) {
            res.statusCode = 400;
            res.setHeader("Content-Type", "application/json");
            res.end(JSON.stringify({ error: "Invalid JSON format." }));
            return;
        }
    } else if (!body) {
        // Collect stream if needed
        try {
            const rawBody = await new Promise((resolve, reject) => {
                let chunks = "";
                req.on("data", chunk => chunks += chunk);
                req.on("end", () => resolve(chunks));
                req.on("error", err => reject(err));
            });
            body = JSON.parse(rawBody || "{}");
        } catch (err) {
            res.statusCode = 400;
            res.setHeader("Content-Type", "application/json");
            res.end(JSON.stringify({ error: "Invalid request payload." }));
            return;
        }
    }

    const message = body?.message?.trim();
    const history = Array.isArray(body?.history) ? body.history : [];

    // Validate message
    if (!message || typeof message !== "string") {
        res.statusCode = 400;
        res.setHeader("Content-Type", "application/json");
        res.end(JSON.stringify({ error: "Message cannot be empty." }));
        return;
    }

    if (message.length > 1000) {
        res.statusCode = 400;
        res.setHeader("Content-Type", "application/json");
        res.end(JSON.stringify({ error: "Message is too long. Maximum allowed is 1,000 characters." }));
        return;
    }

    // Detect configured AI providers
    const geminiKey = process.env.GEMINI_API_KEY;
    const groqKey = process.env.GROQ_API_KEY;
    const openaiKey = process.env.OPENAI_API_KEY;

    if (!geminiKey && !groqKey && !openaiKey) {
        res.statusCode = 200;
        res.setHeader("Content-Type", "application/json");
        res.end(JSON.stringify({
            success: false,
            error: "API_KEY_REQUIRED",
            message: "BR06ai is ready, but requires an API key in server environment variables (e.g. GEMINI_API_KEY).",
            setupInstructions: "Set GEMINI_API_KEY in your deployment environment or .env file (free at https://aistudio.google.com/app/apikey).",
            fallbackKnowledge: knowledge
        }));
        return;
    }

    try {
        let reply = "";
        let providerUsed = "";

        if (geminiKey) {
            providerUsed = "Google Gemini (gemini-1.5-flash)";
            reply = await callGemini(geminiKey, message, history);
        } else if (groqKey) {
            providerUsed = "Groq (llama-3.3-70b-versatile)";
            reply = await callGroq(groqKey, message, history);
        } else if (openaiKey) {
            providerUsed = "OpenAI (gpt-4o-mini)";
            reply = await callOpenAI(openaiKey, message, history);
        }

        res.statusCode = 200;
        res.setHeader("Content-Type", "application/json");
        res.end(JSON.stringify({
            success: true,
            reply: reply,
            provider: providerUsed,
            timestamp: new Date().toISOString()
        }));

    } catch (apiError) {
        console.error("BR06ai Backend Error:", apiError);
        res.statusCode = 500;
        res.setHeader("Content-Type", "application/json");
        res.end(JSON.stringify({
            success: false,
            error: "PROVIDER_ERROR",
            message: "BR06ai encountered an issue reaching the AI provider. Please try again shortly.",
            details: apiError.message
        }));
    }
};
