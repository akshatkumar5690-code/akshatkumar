async function callGemini(apiKey, message, history = []) {
    const systemPrompt = buildSystemPrompt();
    const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`;

    // Format conversation history for Gemini
    const contents = [];
    
    // Add system instruction via user/model primer or systemInstruction field
    contents.push({
        role: "user",
        parts: [{ text: `[System Instruction for BR06ai]\n${systemPrompt}\n\nPlease acknowledge your role as BR06ai.` }]
    });
    contents.push({
        role: "model",
        parts: [{ text: "Got it! I am BR06ai, Akshat's personal AI assistant. I'm ready to help visitors learn about Akshat, his projects like NEXUS AI, his skills, and how to connect." }]
    });

    // Add recent history (up to last 6 turns)
    const recentHistory = history.slice(-6);
    for (const item of recentHistory) {
        if (item.sender === 'user') {
            contents.push({ role: 'user', parts: [{ text: item.text }] });
        } else if (item.sender === 'assistant') {
            contents.push({ role: 'model', parts: [{ text: item.text }] });
        }
    }

    // Add current user message
    contents.push({
        role: "user",
        parts: [{ text: message }]
    });

    const response = await fetch(url, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
            contents: contents,
            generationConfig: {
                temperature: 0.7,
                maxOutputTokens: 800,
            }
        })
    });

    if (!response.ok) {
        const errorText = await response.text();
        throw new Error(`Gemini API error (${response.status}): ${errorText}`);
    }

    const data = await response.json();
    const reply = data.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!reply) {
        throw new Error("No response generated by Gemini model.");
    }

    return reply;
}

async function callGroq(apiKey, message, history = []) {
    const systemPrompt = buildSystemPrompt();
    const messages = [{ role: "system", content: systemPrompt }];

    const recentHistory = history.slice(-6);
    for (const item of recentHistory) {
        messages.push({
            role: item.sender === 'user' ? 'user' : 'assistant',
            content: item.text
        });
    }

    messages.push({ role: "user", content: message });

    const response = await fetch("https://api.groq.com/openai/v1/chat/completions", {
        method: "POST",
        headers: {
            "Content-Type": "application/json",
            "Authorization": `Bearer ${apiKey}`
        },
        body: JSON.stringify({
            model: "llama-3.3-70b-versatile",
            messages: messages,
            temperature: 0.7,
            max_tokens: 800
        })
    });

    if (!response.ok) {
        const errorText = await response.text();
        throw new Error(`Groq API error (${response.status}): ${errorText}`);
    }

    const data = await response.json();
    return data.choices?.[0]?.message?.content || "No response received.";
}

